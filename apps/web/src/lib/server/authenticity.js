/**
 * Known AI image/document generation tool names as they appear in file metadata.
 * Deliberately lowercase — matched against a lowercased scan of the file bytes.
 */
const AI_SIGNATURES = [
	'dall-e', 'dall\u00b7e', 'midjourney', 'stable diffusion', 'stable-diffusion',
	'comfyui', 'comfy ui', 'adobe firefly', 'runwayml', 'runway ml',
	'pika labs', 'kling ai', 'imagen ', 'flux ', 'leonardo ai', 'nightcafe',
	'dreamstudio', 'invokeai', 'invoke ai', 'automatic1111', 'fooocus',
	'ideogram', 'playground ai', 'novelai', 'seaart', 'tensor art',
	'getimg.ai', 'sinkin.ai', 'ai generated', 'generated by ai',
	'diffusion model', 'textual inversion', 'lora:', 'cfg scale',
];

/**
 * Document design tools that produce PDFs — legitimate POS receipt PDFs come
 * from billing software, not consumer document editors.
 */
const DESIGN_TOOL_SIGNATURES = ['canva', 'google docs', 'microsoft word', 'libreoffice writer'];

/**
 * Converts a leading slice of a Uint8Array to a lowercase ASCII string,
 * replacing non-printable bytes with spaces so substring matching works
 * without false splits across word boundaries.
 *
 * @param {Uint8Array} bytes
 * @param {number} maxLen
 * @returns {string}
 */
function _scanText(bytes, maxLen) {
	const end = Math.min(bytes.length, maxLen);
	let out = '';
	for (let i = 0; i < end; i++) {
		const b = bytes[i];
		if (b >= 0x20 && b < 0x7f) {
			// toLower for A-Z
			out += b >= 65 && b <= 90 ? String.fromCharCode(b + 32) : String.fromCharCode(b);
		} else {
			out += ' ';
		}
	}
	return out;
}

/**
 * Scans file bytes for signals that the file may be AI-generated or fabricated,
 * without any external dependencies.  Works for JPEG, PNG, WebP, and PDF.
 *
 * @param {ArrayBuffer} fileBytes
 * @param {string} mimeType
 * @returns {{ risk: 'low' | 'medium' | 'high'; signals: string[] }}
 */
export function scanFileMetadata(fileBytes, mimeType) {
	const bytes = new Uint8Array(fileBytes);
	const signals = [];

	// Scan first 256 KB — all file metadata lives here
	const text = _scanText(bytes, 256 * 1024);

	// ── AI generator name scan (all file types) ───────────────────────
	for (const sig of AI_SIGNATURES) {
		if (text.includes(sig)) {
			signals.push(`AI generator signature detected in file metadata: "${sig}"`);
			break; // One match is conclusive — don't pile on
		}
	}

	// ── JPEG-specific ─────────────────────────────────────────────────
	if (mimeType === 'image/jpeg' || mimeType === 'image/jpg') {
		// Every camera-taken JPEG begins FF D8 FF and carries an Exif APP1.
		// Purely AI-generated images saved as JPEG often have no Exif block at all.
		const isJpeg = bytes[0] === 0xFF && bytes[1] === 0xD8;
		const hasExif = isJpeg && text.slice(0, 64).includes('exif');
		if (isJpeg && !hasExif) {
			signals.push('JPEG contains no Exif block — camera photos always include one');
		}
	}

	// ── PNG-specific ──────────────────────────────────────────────────
	if (mimeType === 'image/png') {
		// Stable Diffusion, ComfyUI, and similar tools embed the full generation
		// prompt and settings into PNG tEXt chunks under keys like "parameters",
		// "prompt", or "workflow".  These strings appear verbatim in the raw bytes.
		const aiPngKeys = ['parameters\x00', 'prompt\x00', 'workflow\x00', 'negative prompt', 'cfg scale', 'sampler'];
		for (const key of aiPngKeys) {
			if (text.includes(key.toLowerCase())) {
				signals.push('PNG contains embedded AI generation parameters (prompt / CFG scale / sampler)');
				break;
			}
		}
	}

	// ── PDF-specific ──────────────────────────────────────────────────
	if (mimeType === 'application/pdf') {
		// Genuine POS-generated receipt PDFs are produced by billing or accounting
		// software.  A receipt PDF whose Creator field names a consumer design tool
		// was almost certainly built manually rather than printed from a terminal.
		for (const tool of DESIGN_TOOL_SIGNATURES) {
			if (text.includes(tool)) {
				signals.push(`PDF was created with a document design tool (${tool}) rather than POS/billing software`);
				break;
			}
		}
	}

	// ── Risk classification ───────────────────────────────────────────
	const hasStrongSignal = signals.some(
		(s) => s.includes('AI generator signature') || s.includes('generation parameters')
	);
	const risk = hasStrongSignal ? 'high' : signals.length >= 2 ? 'medium' : 'low';

	return { risk, signals };
}
